function detectLang() {
  const query = new URLSearchParams(location.search).get("lang");
  if (query === "en" || query === "pl") return query;
  const stored = localStorage.getItem("tk-lang");
  if (stored === "en" || stored === "pl") return stored;
  return "pl";
}

function t(lang, key) {
  return I18N[lang]?.[key] ?? I18N.pl[key] ?? "";
}

function applyLang(lang) {
  const next = I18N[lang] ? lang : "pl";
  document.documentElement.lang = next;
  document.documentElement.classList.remove("lang-pending");
  document.title = t(next, "meta.title");

  const meta = document.querySelector('meta[name="description"]');
  if (meta) meta.setAttribute("content", t(next, "meta.description"));

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const value = t(next, el.getAttribute("data-i18n"));
    if (value) el.textContent = value;
  });

  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const value = t(next, el.getAttribute("data-i18n-html"));
    if (value) el.innerHTML = value;
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const value = t(next, el.getAttribute("data-i18n-aria"));
    if (value) el.setAttribute("aria-label", value);
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
    const value = t(next, el.getAttribute("data-i18n-alt"));
    if (value) el.setAttribute("alt", value);
  });

  document.querySelectorAll(".lang-switch [data-lang]").forEach((btn) => {
    btn.setAttribute("aria-pressed", String(btn.dataset.lang === next));
  });

  localStorage.setItem("tk-lang", next);
  const url = new URL(location.href);
  url.searchParams.set("lang", next);
  history.replaceState(null, "", url);
}

document.querySelectorAll(".lang-switch [data-lang]").forEach((btn) => {
  btn.addEventListener("click", () => applyLang(btn.dataset.lang));
});

applyLang(detectLang());
